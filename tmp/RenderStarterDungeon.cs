var grid = UnityEngine.Object.FindFirstObjectByType<DarkLord.Dungeon.DungeonGrid>();
var go = new UnityEngine.GameObject("Temporary layout review camera");
var camera = go.AddComponent<UnityEngine.Camera>();
camera.CopyFrom(UnityEngine.Camera.main);
camera.transform.position = grid.CellCenter(grid.Layout.Core + new UnityEngine.Vector2Int(-5,1)) + new UnityEngine.Vector3(0,0,-10);
camera.orthographic = true; camera.orthographicSize = 20; camera.aspect = 1280f/900f; camera.ResetWorldToCameraMatrix(); camera.ResetProjectionMatrix();
var target = new UnityEngine.RenderTexture(1280, 900, 24);
camera.targetTexture = target; camera.Render();
var previous = UnityEngine.RenderTexture.active; UnityEngine.RenderTexture.active = target;
var texture = new UnityEngine.Texture2D(1280,900,UnityEngine.TextureFormat.RGB24,false);
texture.ReadPixels(new UnityEngine.Rect(0,0,1280,900),0,0); texture.Apply();
System.IO.File.WriteAllBytes("tmp/StarterDungeonReview.png", UnityEngine.ImageConversion.EncodeToPNG(texture));
UnityEngine.RenderTexture.active = previous; camera.targetTexture = null;
UnityEngine.Object.Destroy(go); UnityEngine.Object.Destroy(texture); target.Release(); UnityEngine.Object.Destroy(target);
return "Rendered starting dungeon overview.";
